"""Generate the demo figures used by the README.

Run from the repository root::

    python scripts/make_figures.py

Writes:
    examples/synthetic/day_NN.png      synthetic input frames
    docs/img/coverage_heatmap.png      plate / heatmap / thresholded mask
    docs/img/coverage_timeseries.png   coverage and count against time

Every image is synthetic. The planted coverage and count are printed next to
the measured values, so the numbers in the README can be regenerated.
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from settle_count import (  # noqa: E402  (import after sys.path setup)
    analyze_coverage,
    count_settled,
    make_demo_series,
    write_demo_images,
)
from settle_count.demo import DEMO_DAYS, DEFAULT_SEED  # noqa: E402

EXAMPLES = ROOT / "examples" / "synthetic"
FIGURES = ROOT / "docs" / "img"
DPI = 200


def _measure(frames):
    """Run the analysis on every frame and print planted versus measured."""
    rows = []
    print(f"{'day':>4}  {'planted cov':>11}  {'measured':>8}  {'error':>7}  "
          f"{'planted n':>9}  {'measured':>8}")
    for frame in frames:
        result = analyze_coverage(frame.image)
        counted = count_settled(frame.image)
        rows.append((frame, result, counted))
        print(
            f"{int(frame.day):>4}  {frame.coverage:>11.3f}  {result.fraction:>8.3f}  "
            f"{result.fraction - frame.coverage:>+7.3f}  {frame.count:>9d}  {counted.count:>8d}"
        )
    coverage_errors = [abs(result.fraction - frame.coverage) for frame, result, _ in rows]
    count_errors = [abs(result.count - frame.count) for frame, _, result in rows]
    print()
    print(f"coverage: mean absolute error {sum(coverage_errors) / len(coverage_errors):.4f} "
          f"({100.0 * sum(coverage_errors) / len(coverage_errors):.2f} percentage points)")
    print(f"count:    mean absolute error {sum(count_errors) / len(count_errors):.2f} individuals")
    return rows


def _figure_heatmap(frame, result):
    """Plate / heatmap / thresholded mask, for one frame."""
    figure, axes = plt.subplots(1, 3, figsize=(13.0, 4.4), constrained_layout=True)

    axes[0].imshow(frame.image)
    axes[0].set_title(f"(a) synthetic plate, day {int(frame.day)}")
    axes[0].set_axis_off()

    heatmap = axes[1].imshow(result.heat, cmap="inferno", vmin=0.0, vmax=1.0)
    axes[1].set_title("(b) CIELAB distance heatmap")
    axes[1].set_axis_off()
    figure.colorbar(heatmap, ax=axes[1], fraction=0.046, pad=0.02,
                    label="relative fouling signal")

    axes[2].imshow(frame.image)
    axes[2].contour(result.mask, levels=[0.5], colors="cyan", linewidths=1.1)
    axes[2].set_title(
        f"(c) thresholded coverage {result.fraction:.3f} "
        f"(planted {frame.coverage:.3f})"
    )
    axes[2].set_axis_off()

    figure.suptitle(
        "settle-count demo - synthetic data only, generated by settle_count.demo",
        fontsize=10,
    )
    destination = FIGURES / "coverage_heatmap.png"
    figure.savefig(destination, dpi=DPI)
    plt.close(figure)
    return destination


def _figure_timeseries(rows):
    """Coverage and count against time, measured versus planted."""
    days = [frame.day for frame, _, _ in rows]
    planted_coverage = [frame.coverage for frame, _, _ in rows]
    measured_coverage = [result.fraction for _, result, _ in rows]
    planted_count = [frame.count for frame, _, _ in rows]
    measured_count = [counted.count for _, _, counted in rows]

    coverage_mae = sum(abs(m - p) for m, p in zip(measured_coverage, planted_coverage)) / len(days)
    count_mae = sum(abs(m - p) for m, p in zip(measured_count, planted_count)) / len(days)

    figure, (left, right) = plt.subplots(1, 2, figsize=(11.0, 4.2), constrained_layout=True)

    left.plot(days, planted_coverage, "k--o", markersize=4, label="planted (ground truth)")
    left.plot(days, measured_coverage, "-o", color="tab:blue", markersize=6, label="measured")
    left.set_xlabel("time (days)")
    left.set_ylabel("coverage fraction")
    left.set_ylim(bottom=0.0)
    left.set_title(f"(a) coverage, MAE {coverage_mae:.3f}")
    left.legend(frameon=False, loc="upper left")
    left.grid(alpha=0.25)

    right.plot(days, planted_count, "k--o", markersize=4, label="planted (ground truth)")
    right.plot(days, measured_count, "-o", color="tab:green", markersize=6, label="measured")
    right.set_xlabel("time (days)")
    right.set_ylabel("individuals")
    right.set_ylim(bottom=0)
    right.set_title(f"(b) count, MAE {count_mae:.2f} individuals")
    right.legend(frameon=False, loc="upper left")
    right.grid(alpha=0.25)

    figure.suptitle(
        "settle-count demo - synthetic data only, generated by settle_count.demo",
        fontsize=10,
    )
    destination = FIGURES / "coverage_timeseries.png"
    figure.savefig(destination, dpi=DPI)
    plt.close(figure)
    return destination


def _report_png(path: Path) -> None:
    """Print byte size and pixel size of a written PNG."""
    with Image.open(path) as image:
        width, height = image.size
    print(f"wrote {path}  {path.stat().st_size} bytes  {width}x{height} px")


def main() -> int:
    """Build the demo data, the figures and the printed validation table."""
    print(f"settle-count demo: days {list(DEMO_DAYS)}, seed {DEFAULT_SEED}")
    frames = make_demo_series()
    written = write_demo_images(EXAMPLES, frames)
    print(f"wrote {len(written)} synthetic frames to {EXAMPLES}")
    print()
    rows = _measure(frames)
    print()
    FIGURES.mkdir(parents=True, exist_ok=True)
    heatmap = _figure_heatmap(frames[-1], rows[-1][1])
    timeseries = _figure_timeseries(rows)
    print()
    _report_png(heatmap)
    _report_png(timeseries)
    return 0


if __name__ == "__main__":
    sys.exit(main())
